/**
 * makeMachine(mutation)
 *
 * A machine with memory management OFF, so a virtual address is a physical address and the
 * EXERCISER phase's memory destinations land where DEPOSIT put SIMH's.
 *
 * @param {string} mutation
 * @returns {Object}
 */
function makeMachine(mutation)
{
    let bus = new BusVAX({'busWidth': VAX.PAWIDTH, 'id': "bus"}, null, null);
    bus.addMemory(0, MEMSIZE, MemoryVAX.TYPE.RAM);
    let mmu = new MMUVAX(bus);
    mmu.setMAPEN(0);

    let cpu = {
        regs: new Int32Array(16),
        psl: 0,
        cc: 0,
        trpirq: 0,
        acc: MMUVAX.accRead(0),                         // kernel; ACC_MASK(KERN)
        decoder: {opnd: new Int32Array(16), spec: 0, rn: 0, va: 0},
        mmu
    };
    let fpu = new VAXFloat(cpu);
    if (mutation) applyMutation(fpu, mutation);
    return {bus, mmu, cpu, fpu};
}

/**
 * runCase(m, c)
 *
 * Run one case on the JS side and return the same shape parseFpop() returns, so the comparison
 * is field by field rather than a stringified blob.
 *
 * @param {Object} m
 * @param {Object} c
 * @returns {Object}
 */
function runCase(m, c)
{
    let {cpu, fpu} = m;
    let d = cpu.decoder;
    for (let i = 0; i < d.opnd.length; i++) d.opnd[i] = 0;
    for (let i = 0; i < c.srcs.length; i++) d.opnd[i] = c.srcs[i] | 0;
    d.spec = c.spec;
    d.rn = c.rn;
    d.va = c.va | 0;
    cpu.psl = c.psl;
    cpu.cc = c.cc;
    cpu.trpirq = 0;
    cpu.regs[c.rn] = c.d0 | 0;
    cpu.regs[(c.rn + 1) & 0xF] = c.d1 | 0;
    try {
        if (!fpu.execute(c.op.opc)) {
            return {err: "fpa.js did not handle opcode " + hex(c.op.opc)};
        }
    } catch (e) {
        if (e instanceof VAXFault) {
            return {ok: false, code: e.code, p1: e.p1 | 0, p2: e.p2 | 0};
        }
        throw e;
    }
    return {ok: true, cc: cpu.cc, trpirq: cpu.trpirq | 0,
        r0: cpu.regs[c.rn] | 0, r1: cpu.regs[(c.rn + 1) & 0xF] | 0};
}

/**
 * describeCase(c)
 *
 * @param {Object} c
 * @returns {string}
 */
function describeCase(c)
{
    return c.op.name + " [" + c.cls + "] opnd=" + c.srcs.map((v) => hex(v, 8)).join(",") +
        " spec=" + hex(c.spec, 2) + " rn=" + c.rn + " va=" + hex(c.va, 8) +
        " psl=" + hex(c.psl, 2) + " cc=" + hex(c.cc);
}

/**
 * compare(sim, js, where, fail)
 *
 * @param {Object} sim
 * @param {Object} js
 * @param {string} where
 * @param {function(string): void} fail
 * @returns {boolean} true if identical
 */
function compare(sim, js, where, fail)
{
    if (js.err) { fail(where + ": " + js.err); return false; }
    if (sim.ok != js.ok) {
        fail(where + ": SIMH " + (sim.ok? "completed" : "aborted " + sim.code) +
            ", we " + (js.ok? "completed" : "faulted " + js.code));
        return false;
    }
    if (!sim.ok) {
        if (sim.code != js.code) {
            fail(where + ": abort code SIMH=" + sim.code + " ours=" + js.code);
            return false;
        }
        /*
         * p1/p2 are only meaningful for the arithmetic abort.  SIMH's reserved-operand and
         * reserved-address aborts leave whatever the last fault put there, which is why they
         * are not compared -- comparing them would be comparing stale globals.
         */
        if (sim.code == ABORT_ARITH && sim.p1 != js.p1) {
            fail(where + ": arithmetic trap parameter SIMH=" + hex(sim.p1) + " ours=" + hex(js.p1));
            return false;
        }
        return true;
    }
    if (sim.cc != js.cc) {
        fail(where + ": cc SIMH=" + hex(sim.cc) + " ours=" + hex(js.cc));
        return false;
    }
    if (sim.trpirq != js.trpirq) {
        fail(where + ": trpirq SIMH=" + hex(sim.trpirq, 8) + " ours=" + hex(js.trpirq, 8));
        return false;
    }
    if (sim.r0 != js.r0 || sim.r1 != js.r1) {
        fail(where + ": result SIMH=" + hex(sim.r0, 8) + "," + hex(sim.r1, 8) +
            " ours=" + hex(js.r0, 8) + "," + hex(js.r1, 8));
        return false;
    }
    return true;
}

