/**
 * mkFrac(rng, bits, pat)
 *
 * @param {function(): number} rng
 * @param {number} bits width of the field
 * @param {string} pat
 * @returns {number}
 */
function mkFrac(rng, bits, pat)
{
    let all = (bits >= 32)? 0xFFFFFFFF : ((1 << bits) - 1);
    switch (pat) {
    case "zero":    return 0;
    case "ones":    return all >>> 0;
    case "high":    return (all & ~(all >>> 4)) >>> 0;
    case "low":     return (all >>> 4) >>> 0;
    case "lowbit":  return 1;
    case "highbit": return (bits >= 32)? 0x80000000 : (1 << (bits - 1));
    case "alt":     return (all & 0xAAAAAAAA) >>> 0;
    default:        return (rnd32(rng) & all) >>> 0;
    }
}

/**
 * genValue(rng, fmt, cls, ctx)
 *
 * Generate one operand of `fmt` belonging to edge class `cls`.  `ctx` accumulates the class
 * labels this value contributes, which is what the coverage floors count.
 *
 * @param {function(): number} rng
 * @param {string} fmt
 * @param {string} cls
 * @param {Set.<string>} ctx
 * @returns {Array.<number>}
 */
function genValue(rng, fmt, cls, ctx)
{
    let f = FMT[fmt];
    let sign = (rng() < 0.5)? 1 : 0;
    let pat = pick(rng, FRAC_PATTERNS);
    let fracHi = mkFrac(rng, (fmt == "F")? 23 : (fmt == "D")? 23 : 20, pat);
    let fracLo = mkFrac(rng, 32, pick(rng, FRAC_PATTERNS));

    switch (cls) {
    case "zero":
        ctx.add("zero");
        return mk(fmt, 0, 0, 0, 0);
    case "resop":
        ctx.add("resop");
        if (rng() < 0.3) {
            ctx.add("negzero");                         // the exact IEEE "-0.0" bit pattern
            return mk(fmt, 1, 0, 0, 0);
        }
        return mk(fmt, 1, 0, fracHi, fracLo);
    case "tinyexp":
        ctx.add("tinyexp");
        return mk(fmt, sign, rndInt(rng, 1, 4), fracHi, fracLo);
    case "maxexp":
        ctx.add("maxexp");
        return mk(fmt, sign, rndInt(rng, f.maxexp - 3, f.maxexp), fracHi, fracLo);
    case "unit":
        return mk(fmt, sign, f.bias + rndInt(rng, -3, 3), fracHi, fracLo);
    default:
        return mk(fmt, sign, rndInt(rng, 1, f.maxexp), fracHi, fracLo);
    }
}

/* ------------------------------------------------------------------------------------------- *
 * Case generation
 * ------------------------------------------------------------------------------------------- */

/*
 * Edge classes for a whole CASE (as opposed to a single operand).  The pair classes exist
 * because the interesting behaviour of add, subtract, multiply and divide is a property of the
 * RELATIONSHIP between the operands, and no per-operand pool can produce it.
 */
const CASE_CLASSES = [
    ["plain",        14],
    ["zero",          8],
    ["resop",         8],
    ["tinyexp",       7],
    ["maxexp",        7],
    ["roundTie",     10],       // exponent difference == sig, sig-1, sig+1
    ["cancellation",  9],
    ["ediff",        10],       // exponent differences straddling the dp_lsh/dp_rsh branches
    ["overflow",      6],
    ["underflow",     6],
    ["divzero",       4],
    ["intovf",        6],
    ["sameval",       5],       // both operands identical: exact cancellation, exact ratio
    ["intbound",      8]        // float-to-integer conversion landing EXACTLY on the limit
];

/*
 * The integer values a float-to-integer conversion must get exactly right, by destination width.
 * The limit is asymmetric -- op_cvtfdgi() compares against `maxv[lnt] + (a.sign? 1 : 0)` -- so
 * -128, -32768 and -2147483648 do NOT overflow while +128, +32768 and +2147483648 do, and the
 * pair either side of each is what proves a port implements that and not `abs(x) > max`.
 */
const INT_BOUNDS = {
    B: [126, 127, 128, 129, -127, -128, -129, 0, 1, -1],
    W: [32766, 32767, 32768, 32769, -32767, -32768, -32769, 0, 1, -1],
    L: [2147483646, 2147483647, 2147483648, 2147483649,
        -2147483647, -2147483648, -2147483649, 65536, -65536, 1]
};

const EDIFFS = [0, 1, 2, 7, 8, 15, 16, 23, 24, 25, 31, 32, 33, 47, 52, 53, 55, 56, 57,
                63, 64, 65, 80, 127, 200, 600, 1500];

/**
 * genSrcs(rng, op, cls, ctx)
 *
 * Produce the operand-queue longwords for one case.  Returns null when the class cannot be
 * applied to this opcode (e.g. `divzero` for a non-divide), so the caller can re-roll.
 *
 * @param {function(): number} rng
 * @param {Object} op
 * @param {string} cls
 * @param {Set.<string>} ctx
 * @returns {?Array.<number>}
 */
function genSrcs(rng, op, cls, ctx)
{
    let srcs = op.srcs;
    let fmt = srcs[0];

    /* integer sources: CVTBF / CVTWD / CVTLG and friends */
    if (fmt == "b" || fmt == "w" || fmt == "l") {
        let v;
        if (fmt == "b") v = rndInt(rng, 0, 0xFF);
        else if (fmt == "w") v = rndInt(rng, 0, 0xFFFF);
        else {
            /*
             * The value that must survive: -2147483648 negates to itself, and `val & LMASK` is
             * what makes op_cvtifdg() cope.  A uniform pool hits it with probability 2^-32.
             */
            v = pick(rng, [0, 1, -1, 0x7FFFFFFF, 0x80000000 | 0, 0x40000000, -0x40000000,
                rnd32(rng), rnd32(rng), rndInt(rng, -1000, 1000)]) | 0;
        }
        if (v == 0) ctx.add("zero");
        return [v | 0];
    }

    let f = FMT[fmt];
    let nsrc = srcs.length;

    /* single-source instructions: MOVx, MNEGx, TSTx, CVTxB/W/L, CVTFD/DF/FG/GF */
    if (nsrc == 1) {
        if (cls == "intbound") {
            /*
             * Only the float-to-integer conversions have an integer limit to sit on.  The half
             * variants matter for CVTRxL specifically: 2147483647.5 rounds UP past the limit
             * while 2147483647.0 does not, and truncating CVTxL disagrees with both.
             */
            if (!INT_BOUNDS[op.dest]) return null;
            let n = pick(rng, INT_BOUNDS[op.dest]);
            let v = fromIntExact(fmt, n, (rng() < 0.4)? pick(rng, [-1, 1]) : 0);
            if (!v) return null;                        // not exact in this format; re-roll
            ctx.add("intbound");
            return v;
        }
        let vcls = cls;
        if (cls == "roundTie" || cls == "cancellation" || cls == "ediff" ||
            cls == "divzero" || cls == "sameval") vcls = "plain";
        if (cls == "overflow" || cls == "intovf") {
            /*
             * CVTFB/W/L overflow needs a large magnitude; CVTFG/CVTDF/CVTGF overflow needs an
             * exponent that will not fit the DESTINATION format once rebiased.
             */
            ctx.add(cls == "intovf"? "intovf" : "overflow");
            return mk(fmt, (rng() < 0.5)? 1 : 0, rndInt(rng, f.bias + 30, f.maxexp),
                mkFrac(rng, (fmt == "F")? 23 : (fmt == "D")? 23 : 20, pick(rng, FRAC_PATTERNS)),
                mkFrac(rng, 32, pick(rng, FRAC_PATTERNS)));
        }
        if (cls == "underflow") {
            ctx.add("tinyexp");
            return mk(fmt, (rng() < 0.5)? 1 : 0, rndInt(rng, 1, 3),
                mkFrac(rng, (fmt == "F")? 23 : (fmt == "D")? 23 : 20, pick(rng, FRAC_PATTERNS)),
                mkFrac(rng, 32, pick(rng, FRAC_PATTERNS)));
        }
        return genValue(rng, fmt, vcls, ctx);
    }

    /* two-source instructions: CMPx, ADDx, SUBx, MULx, DIVx */
    let a, b;
    switch (cls) {

    case "roundTie": {
        /*
         * THE tie.  `a` has exponent E; `b` has exponent E - sig, so b's leading (hidden) bit
         * lands exactly on the round bit of a + b.  sig-1 rounds up cleanly, sig+1 down.  The
         * sticky bits below are varied, because a tie with anything below it is not a tie.
         */
        let d = pick(rng, [f.sig - 1, f.sig, f.sig, f.sig + 1]);
        ctx.add(d == f.sig? "roundTie" : "roundNear");
        ctx.add("ediff1_31");
        let ea = rndInt(rng, f.bias + 4, f.maxexp - 4);
        let eb = ea - d;
        if (eb < 1) { eb = 1; }
        let sticky = (rng() < 0.5);
        a = mk(fmt, 0, ea, mkFrac(rng, (fmt == "F")? 23 : (fmt == "D")? 23 : 20,
            pick(rng, ["zero", "ones", "lowbit", "random"])), mkFrac(rng, 32, "random"));
        b = mk(fmt, (rng() < 0.35)? 1 : 0, eb,
            sticky? mkFrac(rng, (fmt == "F")? 23 : (fmt == "D")? 23 : 20, "random") : 0,
            sticky? mkFrac(rng, 32, "random") : 0);
        break;
    }

    case "cancellation": {
        /*
         * Near-equal magnitudes of opposite sign: the effective subtract cancels the top k bits
         * and norm() has to shift a long way back.  k is swept across the normmask/normtab
         * binary-search boundaries in norm(), which is where a broken shift table hides.
         */
        ctx.add("cancellation");
        ctx.add("ediff0");
        let e = rndInt(rng, f.bias, f.maxexp - 2);
        let k = pick(rng, [0, 1, 2, 3, 4, 7, 8, 15, 16, 17, 23, 31, 32, 33, 40, 51, 52, 55]);
        let sgn = (rng() < 0.5)? 1 : 0;
        let hiBits = (fmt == "G")? 20 : 23;
        let fh = mkFrac(rng, hiBits, "random");
        let fl = mkFrac(rng, 32, "random");
        a = mk(fmt, sgn, e, fh, fl);
        /* flip exactly one low bit k places up, so the difference is 2^k ulp */
        let gh = fh, gl = fl;
        if (k < 32) gl = (fl ^ (1 << k)) >>> 0;
        else gh = (fh ^ (1 << (k - 32))) >>> 0;
        b = mk(fmt, sgn ^ 1, e, gh, gl);
        break;
    }

    case "ediff": {
        let d = pick(rng, EDIFFS);
        if (d == 0) ctx.add("ediff0");
        else if (d < 32) ctx.add("ediff1_31");
        else if (d < 64) ctx.add("ediff32_63");
        else ctx.add("ediff64");
        let ea = rndInt(rng, Math.min(f.maxexp - 2, d + 2), f.maxexp - 1);
        let eb = Math.max(1, ea - d);
        let hiBits = (fmt == "G")? 20 : 23;
        a = mk(fmt, (rng() < 0.5)? 1 : 0, ea, mkFrac(rng, hiBits, pick(rng, FRAC_PATTERNS)),
            mkFrac(rng, 32, pick(rng, FRAC_PATTERNS)));
        b = mk(fmt, (rng() < 0.5)? 1 : 0, eb, mkFrac(rng, hiBits, pick(rng, FRAC_PATTERNS)),
            mkFrac(rng, 32, pick(rng, FRAC_PATTERNS)));
        break;
    }

    case "overflow": {
        if (!op.arith) return null;
        ctx.add("overflow");
        let hiBits = (fmt == "G")? 20 : 23;
        let ea = rndInt(rng, f.maxexp - 2, f.maxexp);
        /* multiply two big ones, or divide a big one by a tiny one */
        let eb = op.div? rndInt(rng, 1, 3) : rndInt(rng, f.maxexp - 2, f.maxexp);
        a = mk(fmt, (rng() < 0.5)? 1 : 0, op.div? eb : ea,
            mkFrac(rng, hiBits, "ones"), mkFrac(rng, 32, "ones"));
        b = mk(fmt, (rng() < 0.5)? 1 : 0, op.div? ea : eb,
            mkFrac(rng, hiBits, "ones"), mkFrac(rng, 32, "ones"));
        break;
    }

    case "underflow": {
        if (!op.arith) return null;
        ctx.add("underflow");
        ctx.add("tinyexp");
        let hiBits = (fmt == "G")? 20 : 23;
        let ea = rndInt(rng, 1, 4);
        let eb = op.div? rndInt(rng, f.maxexp - 4, f.maxexp) : rndInt(rng, 1, 4);
        a = mk(fmt, (rng() < 0.5)? 1 : 0, ea, mkFrac(rng, hiBits, pick(rng, FRAC_PATTERNS)),
            mkFrac(rng, 32, pick(rng, FRAC_PATTERNS)));
        b = mk(fmt, (rng() < 0.5)? 1 : 0, eb, mkFrac(rng, hiBits, pick(rng, FRAC_PATTERNS)),
            mkFrac(rng, 32, pick(rng, FRAC_PATTERNS)));
        break;
    }

    case "divzero": {
        if (!op.div) return null;
        ctx.add("divzero");
        ctx.add("zero");
        a = mk(fmt, 0, 0, 0, 0);                        // opnd[0] is the DIVISOR
        b = genValue(rng, fmt, "plain", ctx);
        break;
    }

    case "sameval": {
        a = genValue(rng, fmt, pick(rng, ["plain", "unit", "tinyexp", "maxexp"]), ctx);
        b = (rng() < 0.5)? a.slice() : a.map((x, i) => (i == 0? (x ^ FPSIGN) | 0 : x));
        ctx.add("ediff0");
        break;
    }

    default:
        a = genValue(rng, fmt, cls, ctx);
        b = genValue(rng, fmt, (rng() < 0.4)? cls : "plain", ctx);
        break;
    }

    if (op.div && getExp(fmt, a) == 0 && !(a[0] & FPSIGN)) ctx.add("divzero");
    let ea = getExp(fmt, a), eb = getExp(fmt, b);
    if (ea && eb) {
        let d = Math.abs(ea - eb);
        if (d == 0) ctx.add("ediff0");
        else if (d < 32) ctx.add("ediff1_31");
        else if (d < 64) ctx.add("ediff32_63");
        else ctx.add("ediff64");
    }
    return a.concat(b);
}

/**
 * genCases(rng, nCases)
 *
 * @param {function(): number} rng
 * @param {number} nCases
 * @returns {Array.<Object>}
 */
function genCases(rng, nCases)
{
    let classes = [];
    for (let [name, w] of CASE_CLASSES) for (let i = 0; i < w; i++) classes.push(name);

    let cases = [];
    let nMem = 0;
    for (let i = 0; i < nCases; i++) {
        /*
         * Round-robin over the opcode table rather than uniform random selection, so the
         * per-opcode floor is met by construction and not by luck.  The class is random.
         */
        let op = OPS[i % OPS.length];
        let cls, srcs, ctx;
        for (let tries = 0; ; tries++) {
            ctx = new Set();
            cls = (tries < 6)? pick(rng, classes) : "plain";
            srcs = genSrcs(rng, op, cls, ctx);
            if (srcs) break;
        }

        /*
         * Destination.  A `spec` above GRN|nPC (0x5F) means memory; anything at or below it is
         * register mode, and the register number is what WRITE_* stores through.  R14/R15 are
         * generated deliberately for quadword destinations, where they are a reserved ADDRESSING
         * mode fault -- SIMH's RSVD_ADDR_FAULT inside WRITE_Q.
         */
        let c = {index: i, op, cls, srcs, cls_set: ctx};
        let wantResad = (op.dest == "Q") && (rng() < 0.02);
        if (wantResad) {
            c.spec = 0x50; c.rn = pick(rng, [14, 15]); c.va = 0;
            ctx.add("resad");
        } else if (op.dest && rng() < 0.42) {
            c.spec = 0x60;
            c.va = (DST_BASE + nMem * DST_STRIDE + (rng() < 0.25? pick(rng, [1, 2, 4, 6]) : 0)) | 0;
            c.rn = rndInt(rng, 0, 13);
            c.slot = nMem++;
            ctx.add("memDest");
        } else {
            c.spec = 0x50;
            c.rn = rndInt(rng, 0, 13);
            c.va = 0;
            if (op.dest) ctx.add("regDest");
        }
        c.d0 = rnd32(rng);
        c.d1 = rnd32(rng);
        c.psl = (rng() < 0.5? PSW_FU : 0) | (rng() < 0.5? PSW_IV : 0);
        c.cc = rndInt(rng, 0, 15);
        cases.push(c);
    }
    return {cases, nMem};
}

