/**
 * runSimh(bin, script, iniPath)
 *
 * @param {string} bin
 * @param {string} script
 * @param {string} iniPath
 * @returns {string} stdout
 */
function runSimh(bin, script, iniPath)
{
    fs.writeFileSync(iniPath, script);
    return execFileSync(bin, [iniPath], {encoding: "utf8", maxBuffer: 1 << 30,
        stdio: ["ignore", "pipe", "pipe"]});
}

/**
 * requireFpSupport(simhBin, scratch)
 *
 * Fails loudly and early if the simulator predates patch 0004, rather than letting every
 * comparison mysteriously report "no FPOP line".  The probe is ADDF3 1.0 + 1.0 = 2.0, whose
 * answer is checked, so a simulator that accepts the command but computes nonsense is caught
 * here rather than 60,000 lines later.
 *
 * @param {string} simhBin
 * @param {string} scratch
 */
function requireFpSupport(simhBin, scratch)
{
    let out = runSimh(simhBin, "set cpu 16m\nshow cpu fpop=41:0:0:50:0:0:0:0:2:4080:4080\nquit\n",
        path.join(scratch, "fpprobe.ini"));
    let m = /^FPOP 041 ok \w+ \w+ (\w+) /m.exec(out);
    if (!m) {
        throw new Error("this simulator does not implement SHOW CPU FPOP=; rebuild it with\n" +
            "    machines/dec/vax/tests/simh/build.sh $TMPDIR/pcjs-vax-simh-fp\n" +
            "which applies patch 0004-fp-differential-support.patch.  SIMH said:\n" + out);
    }
    if (parseInt(m[1], 16) != 0x4100) {
        throw new Error("SHOW CPU FPOP= is present but ADDF3 1.0+1.0 did not give 2.0 (got " +
            m[1] + "); the simulator or the patch is wrong, and nothing below would mean anything.");
    }
}

/**
 * fpopCommand(c)
 *
 * @param {Object} c
 * @returns {string}
 */
function fpopCommand(c)
{
    let f = [hex(c.op.opc), hex(c.psl), hex(c.cc), hex(c.spec), hex(c.rn), hex(c.va),
        hex(c.d0), hex(c.d1), c.srcs.length.toString(16).toUpperCase()];
    for (let v of c.srcs) f.push(hex(v));
    return "show cpu fpop=" + f.join(":");
}

const FPOP_OK_RE    = /^FPOP ([0-9A-F]{3}) ok ([0-9A-F]+) ([0-9A-F]{8}) ([0-9A-F]{8}) ([0-9A-F]{8})$/;
const FPOP_ABORT_RE = /^FPOP ([0-9A-F]{3}) abort (-?\d+) ([0-9A-F]{8}) ([0-9A-F]{8})$/;

/**
 * parseFpop(line)
 *
 * @param {string} line
 * @returns {?Object}
 */
function parseFpop(line)
{
    let m = FPOP_OK_RE.exec(line);
    if (m) {
        return {opc: parseInt(m[1], 16), ok: true, cc: parseInt(m[2], 16),
            trpirq: parseInt(m[3], 16) | 0, r0: parseInt(m[4], 16) | 0, r1: parseInt(m[5], 16) | 0};
    }
    m = FPOP_ABORT_RE.exec(line);
    if (m) {
        return {opc: parseInt(m[1], 16), ok: false, code: parseInt(m[2], 10),
            p1: parseInt(m[3], 16) | 0, p2: parseInt(m[4], 16) | 0};
    }
    return null;
}

