/**
 * mulberry32(a)
 *
 * A tiny deterministic PRNG, so a failing run is reproducible from its seed alone.
 *
 * @param {number} a
 * @returns {function(): number}
 */
function mulberry32(a)
{
    return function() {
        a |= 0; a = (a + 0x6D2B79F5) | 0;
        let t = Math.imul(a ^ (a >>> 15), 1 | a);
        t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
}

/**
 * hex(v, digits)
 *
 * @param {number} v
 * @param {number} [digits]
 * @returns {string}
 */
function hex(v, digits)
{
    let s = (v >>> 0).toString(16).toUpperCase();
    return digits? s.padStart(digits, "0") : s;
}

/**
 * rnd32(rng)
 *
 * @param {function(): number} rng
 * @returns {number} int32
 */
function rnd32(rng)
{
    return ((rng() * 0x10000) & 0xFFFF) | (((rng() * 0x10000) & 0xFFFF) << 16);
}

/**
 * pick(rng, a)
 *
 * @param {function(): number} rng
 * @param {Array} a
 * @returns {*}
 */
function pick(rng, a)
{
    return a[(rng() * a.length) | 0];
}

/**
 * rndInt(rng, lo, hi)  -- inclusive
 *
 * @param {function(): number} rng
 * @param {number} lo
 * @param {number} hi
 * @returns {number}
 */
function rndInt(rng, lo, hi)
{
    return lo + ((rng() * (hi - lo + 1)) | 0);
}

/* ------------------------------------------------------------------------------------------- *
 * Building floating point values
 *
 * All three formats store the fraction WORD-SWAPPED, which is why none of these is a simple
 * shift-and-or.  The layout is derived from vax_fpa.c's unpack routines, not from the
 * architecture manual: unpackd() forms its 64-bit fraction as
 * [WORDSWAP(hi & FD_FRACL | FD_HB)][WORDSWAP(lo)], so the fraction's most significant bits are
 * the LOW word of the LOW longword.
 * ------------------------------------------------------------------------------------------- */

/**
 * mkF(sign, exp, frac)
 *
 * @param {number} sign 0 or 1
 * @param {number} exp  0..0xFF
 * @param {number} frac 23-bit fraction, most significant bit at 22
 * @returns {Array.<number>} one longword
 */
function mkF(sign, exp, frac)
{
    frac = frac & 0x7FFFFF;
    let lw = (sign? FPSIGN : 0) | ((exp & 0xFF) << 7) | ((frac >>> 16) & 0x7F) |
        ((frac & 0xFFFF) << 16);
    return [lw | 0];
}

/**
 * mkD(sign, exp, fracHi, fracLo)
 *
 * @param {number} sign
 * @param {number} exp   0..0xFF
 * @param {number} fracHi fraction bits 54..32 (23 bits)
 * @param {number} fracLo fraction bits 31..0
 * @returns {Array.<number>} two longwords, low first
 */
function mkD(sign, exp, fracHi, fracLo)
{
    fracHi = fracHi & 0x7FFFFF;
    let hi = (sign? FPSIGN : 0) | ((exp & 0xFF) << 7) | ((fracHi >>> 16) & 0x7F) |
        ((fracHi & 0xFFFF) << 16);
    return [hi | 0, WORDSWAP(fracLo) | 0];
}

/**
 * mkG(sign, exp, fracHi, fracLo)
 *
 * @param {number} sign
 * @param {number} exp    0..0x7FF
 * @param {number} fracHi fraction bits 51..32 (20 bits)
 * @param {number} fracLo fraction bits 31..0
 * @returns {Array.<number>} two longwords, low first
 */
function mkG(sign, exp, fracHi, fracLo)
{
    fracHi = fracHi & 0xFFFFF;
    let hi = (sign? FPSIGN : 0) | ((exp & 0x7FF) << 4) | ((fracHi >>> 16) & 0xF) |
        ((fracHi & 0xFFFF) << 16);
    return [hi | 0, WORDSWAP(fracLo) | 0];
}

/**
 * mk(fmt, sign, exp, fracHi, fracLo)
 *
 * @param {string} fmt "F", "D" or "G"
 * @param {number} sign
 * @param {number} exp
 * @param {number} fracHi
 * @param {number} fracLo
 * @returns {Array.<number>}
 */
function mk(fmt, sign, exp, fracHi, fracLo)
{
    if (fmt == "F") return mkF(sign, exp, fracHi);
    if (fmt == "D") return mkD(sign, exp, fracHi, fracLo);
    return mkG(sign, exp, fracHi, fracLo);
}

/**
 * fromIntExact(fmt, n, halfDir)
 *
 * The encoding of `n + halfDir/2` in `fmt`, or null when that value is not EXACTLY representable
 * there.  Exactness is the whole point: this exists to put a float-to-integer conversion on the
 * precise boundary where `maxv[lnt] + (sign? 1 : 0)` decides between a clean answer and integer
 * overflow, and "near 2147483647" is not the same test as "exactly 2147483647".
 *
 * BigInt is used deliberately -- this is test scaffolding, not the shipped path, and getting the
 * 55-bit D fraction right with doubles would be its own bug.
 *
 * @param {string} fmt
 * @param {number} n
 * @param {number} halfDir  -1, 0 or +1: subtract, ignore, or add one half
 * @returns {?Array.<number>}
 */
function fromIntExact(fmt, n, halfDir)
{
    let f = FMT[fmt];
    /* work in units of one half, then take the exponent back down by one */
    let scaled = BigInt(2 * n + halfDir);
    if (scaled == 0n) return mk(fmt, 0, 0, 0, 0);
    let neg = scaled < 0n;
    let a = neg? -scaled : scaled;
    let bits = a.toString(2).length;
    if (bits > f.sig) return null;                      // more significant bits than the format has
    let e = bits - 1;
    let frac = (a << BigInt(f.sig - 1 - e)) & ((1n << BigInt(f.sig - 1)) - 1n);
    let exp = f.bias + e + 1 - 1;                       // +1 for the hidden bit, -1 for the halving
    if (exp < 1 || exp > f.maxexp) return null;
    let fracHi = (fmt == "F")? Number(frac) : Number(frac >> 32n);
    let fracLo = (fmt == "F")? 0 : Number(frac & 0xFFFFFFFFn);
    return mk(fmt, neg? 1 : 0, exp, fracHi, fracLo);
}

/**
 * getExp(fmt, v)
 *
 * @param {string} fmt
 * @param {Array.<number>} v
 * @returns {number} biased exponent
 */
function getExp(fmt, v)
{
    return (fmt == "G")? ((v[0] >>> 4) & 0x7FF) : ((v[0] >>> 7) & 0xFF);
}

/**
 * getSign(fmt, v)
 *
 * @param {string} fmt
 * @param {Array.<number>} v
 * @returns {number} 0 or 1
 */
function getSign(fmt, v)
{
    return (v[0] & FPSIGN)? 1 : 0;
}

